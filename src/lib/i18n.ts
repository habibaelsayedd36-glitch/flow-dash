const DICTS: Record<Locale, Dict> = { en, ar };
export const dictFor = (locale: Locale): Dict => DICTS[locale];
export const dirOf = (locale: Locale) => (locale === "ar" ? "rtl" : "ltr");

/** "{n} runs" + { n: 3 } → "3 runs" */
export function tpl(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Safe lookup for values that come from the database. */
export function label(map: Record<string, string>, key: string | null | undefined): string {
  return key && key in map ? map[key] : (key ?? "");
}

export const num = (n: number) => new Intl.NumberFormat("en-US").format(n);

export function timeAgo(date: Date | string | null, locale: Locale): string {
  if (!date) return "";
  const d = typeof date === "string" ? new Date(date) : date;
  const diff = Math.round((d.getTime() - Date.now()) / 1000);
  const rtf = new Intl.RelativeTimeFormat(locale === "ar" ? "ar-EG-u-nu-latn" : "en", { numeric: "auto" });
  const abs = Math.abs(diff);
  if (abs < 60) return rtf.format(0, "second");
  if (abs < 3600) return rtf.format(Math.round(diff / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), "hour");
  return rtf.format(Math.round(diff / 86400), "day");
}

export function shortDate(date: Date | string | null, locale: Locale): string {
  if (!date) return "";
  const d = typeof date === "string" ? new Date(date) : date;
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-EG-u-nu-latn" : "en-GB", {
    day: "numeric",
    month: "short",
    timeZone: "Africa/Cairo",
  }).format(d);
}

type RuleShape = {
  trigger: string;
  condition: { stage?: string; maxScore?: number; pct?: number; days?: number };
  action: string;
  config: { kind?: string; title?: string; team?: string; stage?: string };
};

export function describeTrigger(a: RuleShape, t: Dict): string {
  const text = label(t.triggerText, a.trigger);
  const n = a.trigger === "listing_generated" ? a.condition.maxScore : a.trigger === "quota_reached" ? a.condition.pct : a.condition.days;
  return tpl(text, { stage: label(t.stage, a.condition.stage), n: n ?? "" });
}

export function describeAction(a: RuleShape, t: Dict): string {
  const kind = a.config.kind === "custom" && a.config.title ? a.config.title : label(t.taskKind, a.config.kind);
  return tpl(label(t.actionText, a.action), {
    kind,
    team: label(t.team, a.config.team),
    stage: label(t.stage, a.config.stage),
  });
}
