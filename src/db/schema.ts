import {
  boolean,
  integer,
  jsonb,
  pgTable,
  real,
  serial,
  text,
  timestamp,
} from "drizzle-orm/pg-core";

export const clients = pgTable("clients", {
  id: serial("id").primaryKey(),
  name: text("name").notNull(),
  contactName: text("contact_name").notNull().default(""),
  phone: text("phone").notNull().default(""),
  plan: text("plan").notNull(),
  marketplaces: jsonb("marketplaces").$type<string[]>().notNull().default([]),
  quota: integer("quota"),
  monthlyFee: integer("monthly_fee").notNull().default(0),
  commissionPct: real("commission_pct").notNull().default(0),
  status: text("status").notNull().default("active"),
  /** Random token for the read-only client portal link. Null = no link. */
  shareToken: text("share_token"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const products = pgTable("products", {
  id: serial("id").primaryKey(),
  clientId: integer("client_id")
    .notNull()
    .references(() => clients.id, { onDelete: "cascade" }),
  name: text("name").notNull(),
  nameAr: text("name_ar").notNull().default(""),
  brand: text("brand").notNull().default(""),
  sku: text("sku").notNull().default(""),
  category: text("category").notNull().default("home"),
  marketplace: text("marketplace").notNull().default("amazon"),
  stage: text("stage").notNull().default("intake"),
  stageEnteredAt: timestamp("stage_entered_at", { withTimezone: true }).notNull().defaultNow(),
  features: text("features").notNull().default(""),
  featuresAr: text("features_ar").notNull().default(""),
  keywords: text("keywords").notNull().default(""),
  /** Units counted on hand at stockAt. Null = stock is not tracked for this product. */
  stock: integer("stock"),
  reorderPoint: integer("reorder_point").notNull().default(0),
  stockAt: timestamp("stock_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const listings = pgTable("listings", {
  id: serial("id").primaryKey(),
  productId: integer("product_id")
    .notNull()
    .references(() => products.id, { onDelete: "cascade" }),
  marketplace: text("marketplace").notNull(),
  status: text("status").notNull().default("draft"),
  /** "ai" = generated by a connected LLM, "template" = built-in rule engine, "sample" = seeded example */
  engine: text("engine").notNull().default("template"),
  model: text("model"),
  tone: text("tone").notNull().default("clear"),
  edited: boolean("edited").notNull().default(false),
  titleEn: text("title_en").notNull().default(""),
  titleAr: text("title_ar").notNull().default(""),
  bulletsEn: jsonb("bullets_en").$type<string[]>().notNull().default([]),
  bulletsAr: jsonb("bullets_ar").$type<string[]>().notNull().default([]),
  descriptionEn: text("description_en").notNull().default(""),
  descriptionAr: text("description_ar").notNull().default(""),
  searchTerms: text("search_terms").notNull().default(""),
  score: integer("score").notNull().default(0),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export type AutomationCondition = {
  stage?: string;
  maxScore?: number;
  pct?: number;
  days?: number;
};

export type AutomationConfig = {
  kind?: string;
  title?: string;
  team?: string;
  dueDays?: number;
  whatsapp?: boolean;
  stage?: string;
};

export const automations = pgTable("automations", {
  id: serial("id").primaryKey(),
  name: text("name").notNull(),
  nameAr: text("name_ar").notNull().default(""),
  trigger: text("trigger").notNull(),
  condition: jsonb("condition").$type<AutomationCondition>().notNull().default({}),
  action: text("action").notNull(),
  config: jsonb("config").$type<AutomationConfig>().notNull().default({}),
  enabled: boolean("enabled").notNull().default(true),
  runCount: integer("run_count").notNull().default(0),
  lastRunAt: timestamp("last_run_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const automationRuns = pgTable("automation_runs", {
  id: serial("id").primaryKey(),
  automationId: integer("automation_id")
    .notNull()
    .references(() => automations.id, { onDelete: "cascade" }),
  /** success | skipped | failed */
  status: text("status").notNull(),
  /** machine code rendered through the dictionary, e.g. task_created */
  code: text("code").notNull(),
  subject: text("subject").notNull().default(""),
  extra: text("extra").notNull().default(""),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const tasks = pgTable("tasks", {
  id: serial("id").primaryKey(),
  kind: text("kind").notNull().default("custom"),
  title: text("title").notNull().default(""),
  clientId: integer("client_id").references(() => clients.id, { onDelete: "cascade" }),
  productId: integer("product_id").references(() => products.id, { onDelete: "cascade" }),
  listingId: integer("listing_id"),
  team: text("team").notNull().default("accounts"),
  dueAt: timestamp("due_at", { withTimezone: true }),
  done: boolean("done").notNull().default(false),
  doneAt: timestamp("done_at", { withTimezone: true }),
  automationId: integer("automation_id"),
  /** Prepared WhatsApp message for a human to send. Nothing is sent automatically. */
  waText: text("wa_text"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const settings = pgTable("settings", {
  key: text("key").primaryKey(),
  value: text("value").notNull().default(""),
});

/** One row of a listing-automation job. */
export type JobItem = {
  /** Values taken from the receiving sheet, keyed by field (sku, name, brand, …). */
  source: Record<string, string>;
  status: "pending" | "done" | "failed";
  engine?: "ai" | "template";
  content?: {
    titleEn: string;
    titleAr: string;
    bulletsEn: string[];
    bulletsAr: string[];
    descriptionEn: string;
    descriptionAr: string;
    searchTerms: string;
  };
  /** Final spec values (sheet values first, then AI estimates). */
  specs?: Record<string, string>;
  /** Spec keys whose value was estimated by AI and must be verified by a person. */
  estimated?: string[];
  /** Spec keys that are still empty. */
  missing?: string[];
  /** Other flags, e.g. "thin_brief". */
  notes?: string[];
  score?: number;
  error?: string;
};

export const jobs = pgTable("jobs", {
  id: serial("id").primaryKey(),
  /** listing | cleanup | shots */
  type: text("type").notNull(),
  title: text("title").notNull().default(""),
  clientId: integer("client_id"),
  marketplace: text("marketplace").notNull().default("amazon"),
  productType: text("product_type").notNull().default(""),
  tone: text("tone").notNull().default("clear"),
  /** draft | running | done */
  status: text("status").notNull().default("draft"),
  total: integer("total").notNull().default(0),
  flagged: integer("flagged").notNull().default(0),
  /** Raw rows of the uploaded receiving sheet (first row = headers). */
  raw: jsonb("raw").$type<string[][]>().notNull().default([]),
  items: jsonb("items").$type<JobItem[]>().notNull().default([]),
  /** Header rows of the seller's own Amazon template, when one was uploaded. */
  template: jsonb("template").$type<string[][] | null>(),
  imported: boolean("imported").notNull().default(false),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

